#!/usr/bin/env python3
"""Restyle the original 1/10/30 µm distance profiles without changing data.

From the repository root:
    python clemson_amp/scripts/accessible_distance_profiles.py

Requires the original native outputs/run manifests and original figure
provenance (generated by poster_figures.py or restored from the poster package).
No models are rerun. The original scripts and figures are preserved.
"""
from __future__ import annotations

import argparse
import csv
from datetime import datetime, timezone
import json
import math
from pathlib import Path

import poster_figures as original

plt, np = original.plt, original.np
STYLES = [
    {"color": "#0072B2", "marker": "o", "linestyle": "-"},
    {"color": "#D55E00", "marker": "s", "linestyle": "--"},
    {"color": "#CC79A7", "marker": "^", "linestyle": ":"},
]
STEM = "particle_distance_profiles_accessible"


def compute_profiles(scenario, groups, results):
    center = scenario["center"]
    edges = np.r_[np.arange(0, 1001, 100), np.arange(2000, 16001, 1000)] / 1000
    profiles = {}
    for group_label, cases in groups:
        for metric in original.METRICS:
            for case in cases:
                data = results[case["name"]][metric]["data"]
                distance = np.hypot(data[:, 0] - center["easting_m"], data[:, 1] - center["northing_m"]) / 1000
                bin_id = np.searchsorted(edges, distance, side="right") - 1
                radii, values, counts = [], [], []
                for index in range(len(edges) - 1):
                    included = bin_id == index
                    if np.count_nonzero(included):
                        radii.append(float(distance[included].mean()))
                        values.append(float(data[included, 2].mean()))
                        counts.append(int(np.count_nonzero(included)))
                profiles[f"{group_label}/{metric}/{case['name']}"] = {
                    "mean_receptor_radius_km": radii,
                    "arithmetic_mean": values,
                    "receptors_in_bin": counts,
                    "zero_bins_hidden_from_log_axis": int(np.count_nonzero(np.asarray(values) <= 0)),
                }
    return {"annulus_edges_km": edges.tolist(), "profiles": profiles}


def render(groups, radial, output):
    plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 18,
                         "axes.spines.top": False, "axes.spines.right": False,
                         "pdf.fonttype": 42, "ps.fonttype": 42})
    fig, axes = plt.subplots(2, 3, figsize=(22, 14), sharex=True)
    for row, (group_label, cases) in enumerate(groups):
        for column, (metric, (label, unit)) in enumerate(original.METRICS.items()):
            ax = axes[row, column]
            for case, style in zip(cases, STYLES):
                profile = radial["profiles"][f"{group_label}/{metric}/{case['name']}"]
                values = np.asarray(profile["arithmetic_mean"])
                ax.plot(profile["mean_receptor_radius_km"], np.where(values > 0, values, np.nan),
                        markersize=6, linewidth=2.3, label=original.case_label(case), **style)
            ax.set(xscale="log", yscale="log", xlim=(0.05, 15.5))
            ax.grid(which="major", alpha=0.18, linewidth=0.8)
            ax.set_ylabel(f"{label} ({unit})", fontsize=22, labelpad=9)
            ax.tick_params(axis="both", which="major", labelsize=18)
            if row == 0:
                ax.set_title(label, fontsize=22, pad=13)
            else:
                ax.set_xlabel("Distance from source (km)", fontsize=22, labelpad=9)
            if column == 0:
                ax.legend(frameon=False, fontsize=16, handlelength=2.8)
                ax.text(0.03, 0.04, group_label, transform=ax.transAxes, fontsize=18)
    fig.suptitle("Particle sensitivity: mean receptor values by distance annulus\n"
                 "Period-mean concentration / accumulated deposition; identical meteorology and equal emissions",
                 fontsize=27, y=0.98)
    fig.text(0.075, 0.025,
             "Arithmetic means across computed receptors in each annulus (100 m bins to 1 km; 1 km bins beyond). Zeros omitted from log axes.\n"
             "These are direction-averaged sample profiles, not downwind trajectories, mass recovery, or a threshold-defined transport range.",
             fontsize=13)
    fig.subplots_adjust(left=0.075, right=0.985, bottom=0.14, top=0.855, hspace=0.27, wspace=0.39)
    fig.canvas.draw()
    axes_font_sizes = [ax.yaxis.label.get_fontsize() for ax in axes.flat]
    axes_font_sizes += [ax.xaxis.label.get_fontsize() for ax in axes[1]]
    if set(axes_font_sizes) != {22.0}:
        raise ValueError("Unexpected axis title size")
    artifacts = []
    original.save_figure(fig, output, STEM, artifacts)
    return artifacts


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project", type=Path, default=Path("clemson_amp"))
    parser.add_argument("--output", type=Path)
    parser.add_argument("--reference", type=Path)
    args = parser.parse_args()
    project = args.project.resolve()
    output = args.output or project / "revisions" / "2026-10-23"
    reference_path = args.reference or project / "figures" / "poster_figures_provenance.json"
    reference = json.loads(reference_path.read_text())
    if reference["status"] != "complete":
        raise ValueError("Original figure provenance is incomplete")
    scenario_path = project / "scenario.json"
    if original.digest(scenario_path) != reference["scenario"]["sha256"]:
        raise ValueError("Scenario differs from the original figure")
    scenario = json.loads(scenario_path.read_text())
    cases = scenario["particle_cases"]
    size_cases = sorted([c for c in cases if math.isclose(c["density_g_cm3"], 1.05)], key=lambda c: c["diameter_um"])
    density_cases = sorted([c for c in cases if math.isclose(c["diameter_um"], 10)], key=lambda c: c["density_g_cm3"])
    if [c["diameter_um"] for c in size_cases] != [1, 10, 30] or [c["density_g_cm3"] for c in density_cases] != [0.9, 1.05, 1.4]:
        raise ValueError("Expected the cases shown in the original attached figure")
    groups = [("Size sensitivity", size_cases), ("Density sensitivity", density_cases)]
    results, model_outputs, reference_xy, reference_time = {}, {}, None, None
    for case in cases:
        results[case["name"]] = {}
        for metric in original.METRICS:
            path = project / "aermod" / case["name"] / metric / "annual.plt"
            execution = original.verify_model_result(project, path)
            parsed = original.parse_plotfile(path, metric)
            if parsed["audit"]["sha256"] != reference["model_outputs"][f"{case['name']}/{metric}"]["sha256"]:
                raise ValueError("Native model output differs from the original figure")
            time_key = (parsed["audit"]["averaging"], parsed["audit"]["hours_in_period"])
            if reference_xy is None:
                reference_xy, reference_time = parsed["data"][:, :2], time_key
            elif not np.array_equal(reference_xy, parsed["data"][:, :2]) or time_key != reference_time:
                raise ValueError("Receptor coordinates or averaging period differ")
            results[case["name"]][metric] = parsed
            model_outputs[f"{case['name']}/{metric}"] = {**parsed["audit"], "verified_native_execution": execution}
    radial = compute_profiles(scenario, groups, results)
    if radial != reference["radial_profiles"]:
        raise ValueError("Numerical profile values differ from the original figure")
    output.mkdir(parents=True, exist_ok=True)
    artifacts = render(groups, radial, output)
    csv_path = output / f"{STEM}_data.csv"
    with csv_path.open("w", newline="") as stream:
        writer = csv.writer(stream, lineterminator="\n")
        writer.writerow(["comparison", "metric", "case", "mean_radius_km", "arithmetic_mean", "unit", "receptors_in_bin"])
        for key, profile in radial["profiles"].items():
            group, metric, case = key.split("/")
            unit = "ug/m3" if metric == "concentration" else "g/m2"
            for radius, value, count in zip(profile["mean_receptor_radius_km"], profile["arithmetic_mean"], profile["receptors_in_bin"]):
                writer.writerow([group, metric, case, radius, value, unit, count])
    artifacts.append({"path": str(csv_path), "sha256": original.digest(csv_path)})
    provenance = {
        "created_utc": datetime.now(timezone.utc).isoformat(), "status": "complete",
        "purpose": "Typography and accessible styling only; no model reruns or numerical changes",
        "original_profile_values_exactly_equal": True,
        "original_figure_provenance_sha256": original.digest(reference_path),
        "scenario_sha256": original.digest(scenario_path),
        "script_sha256": original.digest(Path(__file__)),
        "profile_parser_sha256": original.digest(Path(original.__file__)),
        "typography_pt": {"axis_titles": 22, "panel_titles": 22, "figure_title": 27, "ticks": 18, "legend": 16, "caption": 13},
        "series_styles": STYLES,
        "palette_source": "Okabe and Ito Color Universal Design, https://jfly.uni-koeln.de/color/; blue, vermilion, reddish purple",
        "model_outputs": model_outputs, "radial_profiles": radial, "artifacts": artifacts,
    }
    (output / f"{STEM}_provenance.json").write_text(json.dumps(provenance, indent=2, allow_nan=False) + "\n")
    print(f"Saved {output}; 18 series / 432 profile points exactly match the original figure.")


if __name__ == "__main__":
    main()
